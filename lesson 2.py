# String variables
name = "Adrian Joseph Bayonon"
university = "Northwest Samar State University"
course = "BS Computer Science"

# Integer variables
age = 21
year_level = 3

# Float variables
grade = 95.5
height = 1.70

# Boolean variables
is_student = True
is_graduated = False

# Display string variables
print("PERSONAL INFORMATION")
print("Name:", name)
print("University:", university)
print("Course:", course)

# Display integer variables
print("\nACADEMIC INFORMATION")
print("Age:", age)
print("Year Level:", year_level)

# Display float variables
print("\nOTHER INFORMATION")
print("Grade:", grade)
print("Height:", height)

# Display boolean variables
print("\nSTUDENT STATUS")
print("Currently a student:", is_student)
print("Graduated:", is_graduated)

# Modify variable values
age = 22
grade = 97.0

print("\nUPDATED INFORMATION")
print("Updated Age:", age)
print("Updated Grade:", grade)

